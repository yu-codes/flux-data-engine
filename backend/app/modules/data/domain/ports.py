"""Ports the data domain depends on. Implementations live in infrastructure."""

from __future__ import annotations

from typing import Any, Protocol, runtime_checkable

from app.shared.tabular import Table

from .entities import DataSchema, Dataset, DatasetVersion, Source, SourceType


@runtime_checkable
class SourceReader(Protocol):
    """Reads one external format into the platform's Arrow representation."""

    source_type: SourceType

    def read(self, source: Source, options: dict[str, Any] | None = None) -> Table:
        """Materialise the source (or a slice of it) as a Table."""

    def describe(self, source: Source) -> dict[str, Any]:
        """Connection-level metadata: available tables, file size, and so on."""


class ReaderRegistry(Protocol):
    """Resolves a reader for a source type.

    Injected so the application layer never learns which formats exist, let
    alone how to parse them.
    """

    def __call__(self, source_type: SourceType) -> SourceReader: ...


class SourceRepository(Protocol):
    def add(self, source: Source) -> Source: ...
    def get(self, source_id: str) -> Source | None: ...
    def get_by_name(self, name: str) -> Source | None: ...
    def list(self) -> list[Source]: ...
    def update(self, source: Source) -> Source: ...
    def delete(self, source_id: str) -> None: ...


class DatasetRepository(Protocol):
    def add(self, dataset: Dataset) -> Dataset: ...
    def get(self, dataset_id: str) -> Dataset | None: ...
    def get_by_name(self, name: str) -> Dataset | None: ...
    def list(self) -> list[Dataset]: ...
    def update(self, dataset: Dataset) -> Dataset: ...
    def delete(self, dataset_id: str) -> None: ...

    def add_version(self, version: DatasetVersion) -> DatasetVersion: ...
    def get_version(self, version_id: str) -> DatasetVersion | None: ...
    def list_versions(self, dataset_id: str) -> list[DatasetVersion]: ...
    def next_version_number(self, dataset_id: str) -> int: ...


class SchemaRepository(Protocol):
    def add(self, schema: DataSchema) -> DataSchema: ...
    def get(self, schema_id: str) -> DataSchema | None: ...
    def list(self) -> list[DataSchema]: ...
    def delete(self, schema_id: str) -> None: ...
